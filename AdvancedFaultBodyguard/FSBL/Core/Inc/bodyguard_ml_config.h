#ifndef BODYGUARD_ML_CONFIG_H
#define BODYGUARD_ML_CONFIG_H

#define BODYGUARD_ML_CPU 0
#define BODYGUARD_ML_NPU 1

/* Change this value, then Clean + Build. Can also be overridden with -D. */
#ifndef BODYGUARD_ML_BACKEND
#define BODYGUARD_ML_BACKEND BODYGUARD_ML_NPU
#endif
#if BODYGUARD_ML_BACKEND != BODYGUARD_ML_CPU && BODYGUARD_ML_BACKEND != BODYGUARD_ML_NPU
#error "Invalid BODYGUARD_ML_BACKEND: use BODYGUARD_ML_CPU or BODYGUARD_ML_NPU"
#endif

#ifndef BODYGUARD_ML_ADC_CHANNEL
#define BODYGUARD_ML_ADC_CHANNEL 1
#endif
#if BODYGUARD_ML_ADC_CHANNEL != 1 && BODYGUARD_ML_ADC_CHANNEL != 2
#error "BODYGUARD_ML_ADC_CHANNEL must be 1 or 2"
#endif

#define BODYGUARD_ADC_SAMPLES 6000u
#define BODYGUARD_ML_TIMEOUT_MS 5000u
#endif
