static int compare_float(const void *a, const void *b)
{
    const float fa = *(const float *)a;
    const float fb = *(const float *)b;
    return (fa > fb) - (fa < fb);
}

static float median_u8_first_samples(const uint8_t *x, uint32_t n)
{
    uint8_t tmp[NN_PREPROCESS_BASELINE_SAMPLES];
    uint32_t i;

    for (i = 0; i < n; ++i)
    {
        tmp[i] = x[i];
    }

    for (i = 1; i < n; ++i)
    {
        uint8_t key = tmp[i];
        int32_t j = (int32_t)i - 1;
        while (j >= 0 && tmp[j] > key)
        {
            tmp[j + 1] = tmp[j];
            --j;
        }
        tmp[j + 1] = key;
    }

    if ((n & 1u) == 0u)
    {
        return 0.5f * ((float)tmp[(n / 2u) - 1u] + (float)tmp[n / 2u]);
    }
    return (float)tmp[n / 2u];
}

static float percentile_sorted(const float *sorted, uint32_t n, float percentile)
{
    const float pos = ((float)n - 1.0f) * percentile;
    const uint32_t lo = (uint32_t)floorf(pos);
    uint32_t hi = lo + 1u;
    const float frac = pos - (float)lo;

    if (hi >= n)
    {
        hi = n - 1u;
    }
    return sorted[lo] + (sorted[hi] - sorted[lo]) * frac;
}

static uint16_t detect_event_index(const uint8_t *adc_buffer)
{
    uint32_t best_index = NN_PREPROCESS_EVENT_SEARCH_START;
    float best_energy = -1.0f;
    const int32_t half = (int32_t)NN_PREPROCESS_EVENT_SMOOTH / 2;
    uint32_t i;

    for (i = NN_PREPROCESS_EVENT_SEARCH_START; i < (NN_PREPROCESS_EVENT_SEARCH_END - 1u); ++i)
    {
        float sum = 0.0f;
        int32_t k;
        for (k = -half; k <= half; ++k)
        {
            const int32_t diff_index = (int32_t)i + k;
            if (diff_index >= 0 && diff_index < ((int32_t)NN_PREPROCESS_ADC_SAMPLES - 1))
            {
                const int32_t a = (int32_t)adc_buffer[diff_index + 1];
                const int32_t b = (int32_t)adc_buffer[diff_index];
                sum += fabsf((float)(a - b));
            }
        }
        if (sum > best_energy)
        {
            best_energy = sum;
            best_index = i;
        }
    }

    return (uint16_t)(best_index + 1u);
}

static void build_crop(
    const uint8_t *adc_buffer,
    float baseline,
    uint16_t event_index,
    float crop[NN_PREPROCESS_CROP_SAMPLES])
{
    const int32_t start = (int32_t)event_index - (int32_t)NN_PREPROCESS_CROP_PRE;
    uint32_t i;

    for (i = 0; i < NN_PREPROCESS_CROP_SAMPLES; ++i)
    {
        const int32_t source_index = start + (int32_t)i;
        if (source_index >= 0 && source_index < (int32_t)NN_PREPROCESS_ADC_SAMPLES)
        {
            crop[i] = (float)adc_buffer[source_index] - baseline;
        }
        else
        {
            crop[i] = 0.0f;
        }
    }
}

static int8_t quantize_feature(float x, uint32_t *clipped_low, uint32_t *clipped_high)
{
    int32_t q = (int32_t)lrintf((x / NN_PREPROCESS_INPUT_SCALE) + (float)NN_PREPROCESS_INPUT_ZERO_POINT);
    if (q < -128)
    {
        q = -128;
        ++(*clipped_low);
    }
    else if (q > 127)
    {
        q = 127;
        ++(*clipped_high);
    }
    return (int8_t)q;
}

nn_preprocess_status_t nn_preprocess_adc_u8_to_float(
    const uint8_t adc_buffer[NN_PREPROCESS_ADC_SAMPLES],
    float network_input_float[NN_PREPROCESS_INPUT_FEATURES],
    nn_preprocess_workspace_t *workspace,
    nn_preprocess_info_t *info)
{
    uint32_t i;
    float q25;
    float q50;
    float q75;
    float iqr;
    uint16_t event_index;
    float baseline;
    float feature_min = INFINITY;
    float feature_max = -INFINITY;

    if (adc_buffer == NULL || network_input_float == NULL || workspace == NULL)
    {
        return NN_PREPROCESS_NULL_POINTER;
    }

    baseline = median_u8_first_samples(adc_buffer, NN_PREPROCESS_BASELINE_SAMPLES);
    event_index = detect_event_index(adc_buffer);
    build_crop(adc_buffer, baseline, event_index, workspace->crop);

    for (i = 0; i < NN_PREPROCESS_INPUT_FEATURES; ++i)
    {
        const float d = workspace->crop[i + 1u] - workspace->crop[i];
        workspace->derivative[i] = d;
        workspace->sort_buffer[i] = d;
    }

    qsort(workspace->sort_buffer, NN_PREPROCESS_INPUT_FEATURES, sizeof(float), compare_float);
    q25 = percentile_sorted(workspace->sort_buffer, NN_PREPROCESS_INPUT_FEATURES, 0.25f);
    q50 = percentile_sorted(workspace->sort_buffer, NN_PREPROCESS_INPUT_FEATURES, 0.50f);
    q75 = percentile_sorted(workspace->sort_buffer, NN_PREPROCESS_INPUT_FEATURES, 0.75f);
    iqr = q75 - q25;
    if (fabsf(iqr) < NN_PREPROCESS_EPSILON)
    {
        iqr = NN_PREPROCESS_EPSILON;
    }

    for (i = 0; i < NN_PREPROCESS_INPUT_FEATURES; ++i)
    {
        const float robust = (workspace->derivative[i] - q50) / iqr;
        const float standardized = (robust - g_feature_mean[i]) / g_feature_std[i];
        network_input_float[i] = standardized;
        if (standardized < feature_min)
        {
            feature_min = standardized;
        }
        if (standardized > feature_max)
        {
            feature_max = standardized;
        }
    }

    if (info != NULL)
    {
        info->event_index = event_index;
        info->baseline = baseline;
        info->derivative_median = q50;
        info->derivative_q25 = q25;
        info->derivative_q75 = q75;
        info->derivative_iqr = iqr;
        info->feature_min = feature_min;
        info->feature_max = feature_max;
        info->clipped_low = 0u;
        info->clipped_high = 0u;
    }

    return NN_PREPROCESS_OK;
}

nn_preprocess_status_t nn_preprocess_adc_u8_to_int8(
    const uint8_t adc_buffer[NN_PREPROCESS_ADC_SAMPLES],
    int8_t network_input[NN_PREPROCESS_INPUT_FEATURES],
    nn_preprocess_workspace_t *workspace,
    nn_preprocess_info_t *info)
{
    nn_preprocess_status_t status;
    uint32_t clipped_low = 0u;
    uint32_t clipped_high = 0u;
    uint32_t i;

    if (network_input == NULL || workspace == NULL)
    {
        return NN_PREPROCESS_NULL_POINTER;
    }

    status = nn_preprocess_adc_u8_to_float(adc_buffer, workspace->derivative, workspace, info);
    if (status != NN_PREPROCESS_OK)
    {
        return status;
    }

    for (i = 0; i < NN_PREPROCESS_INPUT_FEATURES; ++i)
    {
        network_input[i] = quantize_feature(workspace->derivative[i], &clipped_low, &clipped_high);
    }

    if (info != NULL)
    {
        info->clipped_low = clipped_low;
        info->clipped_high = clipped_high;
    }

    return NN_PREPROCESS_OK;
}
